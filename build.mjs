import {readFile,writeFile} from 'node:fs/promises';
const flow=await readFile(new URL('flow.js',import.meta.url),'utf8');
const ui=await readFile(new URL('ui.js',import.meta.url),'utf8');
// Plain script supports both the local server and opening index.html directly.
const bundle=`// Generated by node build.mjs. Edit flow.js and ui.js.\n(()=>{\n'use strict';\n${flow.replace(/^export /gm,'')}\n${ui.replace(/^import .*;\r?\n/gm,'')}\n})();\n`;
await writeFile(new URL('app.js',import.meta.url),bundle);
